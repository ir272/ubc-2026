// Writes ROUNDS.md from critics/*.json: one section per piece, one line per critic round.
import fs from 'node:fs';
const dir = new URL('../critics/', import.meta.url);
const by = {};
for (const f of fs.readdirSync(dir)) {
  const m = /^(.+)-r(\d+)\.json$/.exec(f);
  if (!m) continue;
  let v; try { v = JSON.parse(fs.readFileSync(new URL(f, dir), 'utf8')); } catch { continue; }
  (by[m[1]] ||= []).push({ r: Number(m[2]), v });
}
const order = (k) => (k.startsWith('voice') ? 0 : k.startsWith('script') ? 1 : 2) + k;
let out = '# Round log\n\nOne line per critic round. Every critic had fresh context and compared ours with the bar directly:\nvoices and script beats against real Monster Prom lines and the real shows\' formats, stage pieces\nagainst frames and clips from official footage. "ours" means the critic picked ours.\nGenerated by `node tools/rounds.mjs` from `critics/*.json`, which hold the full verdicts.\n';
for (const k of Object.keys(by).sort((a, b) => order(a).localeCompare(order(b)))) {
  out += `\n## ${k}\n\n`;
  for (const { r, v } of by[k].sort((a, b) => a.r - b.r)) {
    const extra = typeof v.genericPercent === 'number' ? `, ${Math.round(v.genericPercent)}% of lines flagged` : '';
    const gap = String(v.biggestGap || '').replace(/\s+/g, ' ').trim();
    out += `- Round ${r}: **${v.winner === 'ours' ? 'ours' : 'the bar'}**${extra}. ${v.winner === 'ours' ? 'Remaining note' : 'Biggest gap'}: ${gap}\n`;
  }
}
fs.writeFileSync(new URL('../ROUNDS.md', import.meta.url), out);
console.log('ROUNDS.md', Object.keys(by).length, 'pieces');
