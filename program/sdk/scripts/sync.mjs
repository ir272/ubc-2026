// Copies the program IDL (and DEPLOYED.json if present) into src/ as TS modules.
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const idlSrc = join(here, '../../target/idl/arena.json');
const depSrc = join(here, '../../DEPLOYED.json');
if (existsSync(idlSrc)) {
  const idl = readFileSync(idlSrc, 'utf8');
  writeFileSync(join(here, '../src/idl.json'), idl);
  writeFileSync(join(here, '../src/idl.ts'), `// generated by scripts/sync.mjs from target/idl/arena.json\nexport const IDL = ${idl.trim()} as const;\nexport type ArenaIdl = typeof IDL;\n`);
}
const dep = existsSync(depSrc) ? readFileSync(depSrc, 'utf8').trim() : 'null';
writeFileSync(join(here, '../src/deployed.ts'), `// generated by scripts/sync.mjs from program/DEPLOYED.json\nexport const DEPLOYED: { cluster: string; programId: string; mint: string; config: string } | null = ${dep};\n`);
